import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendDirectory = resolve(scriptDirectory, "..");
const versionFile = resolve(frontendDirectory, "..", "..", "SSWVersion.props");
const source = readFileSync(versionFile, "utf8");
const version = source.match(/<SSWVersion>\s*([^<]+?)\s*<\/SSWVersion>/u)?.[1];

if (!version) throw new Error(`Unable to read SSWVersion from ${versionFile}`);

const outputFile = resolve(frontendDirectory, "src", "release-info.generated.ts");
mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(
  outputFile,
  `// Generated by scripts/generate-release-info.mjs. Do not edit.\n` +
    `export const releaseInfo = ${JSON.stringify({ version, builtAt: new Date().toISOString() })} as const;\n`,
  "utf8",
);
