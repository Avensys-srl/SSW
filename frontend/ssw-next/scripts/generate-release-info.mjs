import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendDirectory = resolve(scriptDirectory, "..");
const versionFile = resolve(frontendDirectory, "..", "..", "SSWVersion.props");
const historyFile = resolve(frontendDirectory, "..", "..", "SSWLib", "History.txt");
const italianHistoryFile = resolve(frontendDirectory, "..", "..", "SSWLib", "History.it.txt");
const source = readFileSync(versionFile, "utf8");
const version = source.match(/<SSWVersion>\s*([^<]+?)\s*<\/SSWVersion>/u)?.[1];

if (!version) throw new Error(`Unable to read SSWVersion from ${versionFile}`);

const parseHistory = (path) => {
  const entries = [];
  let currentRelease;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/u)) {
    const heading = line.match(/^\s*(\d+\.\d+\.\d+(?:\.\d+)?)(?:\s+-\s+(\d{4}-\d{2}-\d{2}))?\s*$/u);
    if (heading) {
      currentRelease = { version: heading[1], date: heading[2] ?? "", changes: [] };
      entries.push(currentRelease);
      continue;
    }
    if (/^\s*-{3,}\s*$/u.test(line)) continue;
    const change = line.match(/^\s*-\s+(.+?)\s*$/u);
    if (currentRelease && change) currentRelease.changes.push(change[1]);
  }
  return entries;
};

const history = parseHistory(historyFile);
const italianHistory = parseHistory(italianHistoryFile);
if (history.length !== italianHistory.length) {
  throw new Error("English and Italian changelogs contain different release counts.");
}
for (let i = 0; i < history.length; i++) {
  const english = history[i];
  const italian = italianHistory[i];
  if (english.version !== italian.version || english.changes.length !== italian.changes.length) {
    throw new Error(`English and Italian changelogs do not align at release ${english.version}.`);
  }
  english.changesIt = italian.changes;
}

const outputFile = resolve(frontendDirectory, "src", "release-info.generated.ts");
mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(
  outputFile,
  `// Generated by scripts/generate-release-info.mjs. Do not edit.\n` +
  `export const releaseInfo = ${JSON.stringify({ version, builtAt: new Date().toISOString(), updatedAt: history.find((entry) => entry.date)?.date ?? "", history })} as const;\n`,
  "utf8",
);
